test('opens a compound child conversation and pages long seed IDs on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 844 })
  await page.goto(scenarioRunRoutePath('00000000-0000-0000-0000-000000002390'))
  const panel = page.getByRole('region', { name: 'Paired outcomes', exact: true })
  await panel.getByLabel('Baseline group').selectOption('baseline')
  await panel.getByLabel('Attack group').selectOption('attack')
  await panel.getByRole('button', { name: 'Compare outcomes' }).click()
  await panel.getByRole('button', { name: 'Failure → Success' }).click()
  const details = panel.getByRole('region', { name: 'Failure → Success pair details' })
  await expect(details).toContainText('25 of 31 pairs shown')
  await expect(details).toContainText('Linked child outcome: success')
  expect(await panel.evaluate((element) => element.scrollWidth > element.clientWidth)).toBe(false)
  const nextPage = page.waitForResponse((response) => response.url().includes('/paired-outcomes/details?') && response.url().includes('cursor='))
  await details.getByRole('button', { name: 'Load more Failure → Success pairs' }).click()
  expect((await nextPage).status()).toBe(200)
  await expect(details).toContainText('31 of 31 pairs shown')
  const baseline = details.getByRole('link', { name: 'Open baseline conversation', exact: true }).first()
  const baselinePath = await baseline.getAttribute('href')
  const child = details.getByRole('link', { name: 'Open attack child conversation', exact: true })
  await child.click()
  await expect(page).toHaveURL(/\/attacks\/[^/]+\/conversations\/[^/]+\?scenarioResultId=00000000-0000-0000-0000-000000002390/)
  await expect(page.getByText('Offline objective: a')).toBeVisible()
  if (!baselinePath) throw new Error('Missing baseline conversation link')
  await page.goto(baselinePath)
  await expect(page.getByText('Offline objective: a')).toBeVisible()
})

test('offers a usable mobile retry after a real network failure', async ({ page, context }) => {
  await page.setViewportSize({ width: 320, height: 844 })
  await page.goto(run)
  const panel = page.getByRole('region', { name: 'Paired outcomes', exact: true })
  await panel.getByLabel('Baseline group').selectOption('baseline')
  await panel.getByLabel('Attack group').selectOption('attack')
  await panel.getByRole('button', { name: 'Compare outcomes' }).click()
  const expand = panel.getByRole('button', { name: 'Failure → Success' })
  await expect(expand).toBeVisible()
  await context.setOffline(true)
  await expand.click()
  const retry = panel.getByRole('button', { name: 'Retry Failure → Success pairs' })
  await expect(retry).toBeVisible()
  expect(await panel.evaluate((element) => element.scrollWidth > element.clientWidth)).toBe(false)
  expect((await retry.boundingBox())?.height).toBeGreaterThanOrEqual(44)
  await context.setOffline(false)
  await retry.click()
  await expect(panel.getByRole('region', { name: 'Failure → Success pair details' })).toContainText('Logical seed: a')
})
