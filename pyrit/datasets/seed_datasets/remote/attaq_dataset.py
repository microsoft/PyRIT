import logging
from collections.abc import Sequence
from enum import Enum

from typing_extensions import override

from pyrit.datasets.seed_datasets.remote.remote_dataset_loader import (
    _RemoteDatasetLoader,
)
from pyrit.models import Modality, SeedDataset, SeedPrompt

logger = logging.getLogger(__name__)

_AUTHORS: list[str] = [
    "George Kour",
    "Marcel Zalmanovici",
    "Naama Zwerdling",
    "Esther Goldbraich",
    "Ora Nova Fandina",
    "Ateret Anaby-Tavor",
    "Orna Raz",
    "Eitan Farchi",
]
_GROUPS: list[str] = ["IBM Research"]
_DATASET_URL = "https://huggingface.co/datasets/ibm-research/AttaQ"
_DESCRIPTION = (
    "AttaQ is IBM Research's set of adversarial questions written to draw harmful answers out of "
    "a model, each labelled with one of seven harm categories."
)


class AttaQCategory(Enum):
    """AttaQ harm categories, using the exact ``label`` values in the dataset."""

    DECEPTION = "deception"
    DISCRIMINATION = "discrimination"
    EXPLICIT_CONTENT = "explicit_content"
    HARMFUL_INFO = "harmful_info"
    PII = "pii"
    SUBSTANCE_ABUSE = "substance_abuse"
    VIOLENCE = "violence"


class _AttaQDataset(_RemoteDatasetLoader):
    """
    Loader for AttaQ, IBM Research's 1,402 adversarial questions for probing harmful responses.

    Each question is labelled with one of seven harm categories. The questions were extracted
    from Anthropic's ``hh-rlhf`` red-teaming data, generated by LLMs in the same style, or
    generated by LLMs from a list of crime types. Every row becomes one ``SeedPrompt`` with
    ``harm_categories=[label]`` and the row's ``additional_info`` (where the question came
    from) in ``metadata``.

    Reference: [@kour2023unveiling]

    HuggingFace: https://huggingface.co/datasets/ibm-research/AttaQ (MIT licence), pinned to a
    known revision.

    Note: The dataset card says: "We restrict the usage of the dataset to make models less
    harmful."

    Warning: These questions are written to elicit harmful responses and may contain offensive
    content.
    """

    HF_DATASET_NAME: str = "ibm-research/AttaQ"
    HF_REVISION: str = "5346565948b1809de748d304b7b70198d71a16c9"
    HF_SPLIT: str = "train"

    modalities: tuple[Modality, ...] = (Modality.TEXT,)
    harm_categories: list[str] = [category.value for category in AttaQCategory]
    size: str = "large"
    tags: frozenset[str] = frozenset({"safety"})

    def __init__(
        self,
        *,
        categories: Sequence[AttaQCategory] | None = None,
    ) -> None:
        """
        Initialize the AttaQ dataset loader.

        Args:
            categories: Harm categories to load. ``None`` loads all seven categories.

        Raises:
            ValueError: If ``categories`` is empty or contains a non-enum value.
        """
        if categories is not None:
            self._validate_enums(categories, AttaQCategory, "category")
            if len(categories) == 0:
                raise ValueError("categories must contain at least one AttaQCategory.")
        self._categories: frozenset[AttaQCategory] | None = frozenset(categories) if categories else None

    @property
    @override
    def dataset_name(self) -> str:
        """The dataset name."""
        return "attaq"

    @override
    async def _fetch_dataset_async(self, *, cache: bool = True) -> SeedDataset:
        """
        Fetch AttaQ from HuggingFace and return the selected categories as a SeedDataset.

        Args:
            cache: Whether to cache the fetched dataset. Defaults to True.

        Returns:
            SeedDataset: One prompt per AttaQ question.

        Raises:
            ValueError: If a row has an unknown label or an empty question, or the dataset is empty.
        """
        rows = await self._fetch_from_huggingface_async(
            dataset_name=self.HF_DATASET_NAME,
            split=self.HF_SPLIT,
            cache=cache,
            revision=self.HF_REVISION,
        )

        known_labels = {category.value for category in AttaQCategory}
        wanted_labels = None if self._categories is None else {category.value for category in self._categories}
        seed_prompts: list[SeedPrompt] = []
        for index, row in enumerate(rows):
            label = row.get("label")
            question = row.get("input")
            if label not in known_labels:
                raise ValueError(f"AttaQ row {index} has an unknown label: {label!r}.")
            if not isinstance(question, str) or not question:
                raise ValueError(f"AttaQ row {index} has no question.")
            if wanted_labels is not None and label not in wanted_labels:
                continue
            seed_prompts.append(
                SeedPrompt(
                    value=question,
                    data_type="text",
                    dataset_name=self.dataset_name,
                    harm_categories=[label],
                    description=_DESCRIPTION,
                    authors=_AUTHORS,
                    groups=_GROUPS,
                    source=_DATASET_URL,
                    metadata={"additional_info": row.get("additional_info") or ""},
                )
            )

        if not seed_prompts:
            raise ValueError("SeedDataset cannot be empty. Check your filter criteria.")

        logger.info("Loaded %s prompts from AttaQ", len(seed_prompts))
        return SeedDataset(seeds=seed_prompts, dataset_name=self.dataset_name)
