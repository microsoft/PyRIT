import mimetypes
import re
from collections.abc import Callable
from pathlib import Path
from typing import Any, ClassVar, Literal
from urllib.parse import urlencode

import aiofiles
import httpx

from pyrit.common.deprecation import print_deprecation_message
from pyrit.models import (
    ComponentIdentifier,
    Message,
    MessagePiece,
    construct_response_from_request,
)
from pyrit.prompt_target.common.target_capabilities import TargetCapabilities
from pyrit.prompt_target.common.target_configuration import TargetConfiguration
from pyrit.prompt_target.common.target_trace_config import TargetTraceConfig, request_trace_headers
from pyrit.prompt_target.common.utils import limit_requests_per_minute
from pyrit.prompt_target.http_target.http_target import HTTPTarget

logger = logging.getLogger(__name__)


class HTTPXAPITarget(HTTPTarget):
    """
    A subclass of HTTPTarget that *only* does "API mode" (no raw HTTP request).
    This is a simpler approach for uploading files or sending JSON/form data.

    Additionally, if 'file_path' is not provided in the constructor,
    we attempt to pull it from the prompt's `converted_value`, assuming
    it's a local file path generated by a Converter (like PDFConverter).
    """

    _PATH_TYPES: frozenset[str] = frozenset({"image_path", "audio_path", "video_path", "binary_path"})
    upload_directory_parameter: ClassVar[str | None] = "allowed_upload_directory"
    _DEFAULT_CONFIGURATION: TargetConfiguration = TargetConfiguration(
        capabilities=TargetCapabilities(
            supports_multi_turn=True,
            input_modalities=frozenset(
                {
                    frozenset(["text"]),
                    frozenset(["image_path"]),
                    frozenset(["audio_path"]),
                    frozenset(["video_path"]),
                    frozenset(["binary_path"]),
                }
            ),
        )
    )
    _CREDENTIAL_QUERY_NAME_TOKENS: ClassVar[frozenset[str]] = frozenset(
        {
            "key",
            "keys",
            "token",
            "tokens",
            "secret",
            "secrets",
            "password",
            "passwords",
            "passwd",
            "pwd",
            "auth",
            "authorization",
            "credential",
            "credentials",
            "sig",
            "signature",
            "signatures",
            "jwt",
            "assertion",
            "assertions",
            "bearer",
            "apikey",
            "oauth",
        }
    )

    @classmethod
    def _is_sensitive_query_param(cls, key: str) -> bool:
        # Match credential parameter names by word, not by substring: `design`
        # contains "sig" and `author` contains "auth", but neither is a
        # credential, and stripping them collapses distinct URLs into one
        # identifier. Splitting on non-alphanumeric separators and on camelCase
        # word boundaries keeps compound credential names (`api_key`,
        # `client_secret`, `access_token`, `accessToken`, `clientSecret`)
        # sensitive while leaving unrelated names intact.
        tokens = {
            token.lower()
            for token in re.split(r"[^a-zA-Z0-9]+|(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", key)
            if token
        }
        if tokens & cls._CREDENTIAL_QUERY_NAME_TOKENS:
            return True
        return key.lower() in {"code", "pass"}

    @classmethod
    def _redact_url_for_identifier(cls, url: httpx.URL | str) -> str:
        parsed_url = httpx.URL(url) if not isinstance(url, httpx.URL) else url
        # The fragment is never part of the HTTP request target, and can carry
        # credentials (e.g. '#access_token=...'), so it is dropped entirely.
        cleaned_url = parsed_url.copy_with(username=None, password=None, fragment=None)
        if cleaned_url.query:
            query_items = [(k, v) for k, v in cleaned_url.params.multi_items() if not cls._is_sensitive_query_param(k)]
            new_query = urlencode(query_items) if query_items else None
            cleaned_url = cleaned_url.copy_with(query=new_query.encode("ascii") if new_query else None)
        return str(cleaned_url)

    @staticmethod
    def _merge_base_and_url(base_url: httpx.URL, url: httpx.URL) -> httpx.URL:
        """
        Resolve ``url`` against ``base_url`` exactly like ``httpx.AsyncClient`` does.

        ``httpx.AsyncClient._merge_url`` ensures the base URL ends in ``'/'`` and
        appends the request path with any leading ``'/'`` stripped, so relative
        URLs and absolute paths are appended to the base path rather than
        replacing it — unlike ``httpx.URL.join``, which RFC 3986-resolves and can
        collapse distinct base paths into the same identifier endpoint.

        Returns:
            The URL the client would actually send the request to.
        """
        base = base_url
        if not base.raw_path.endswith(b"/"):
            base = base.copy_with(raw_path=base.raw_path + b"/")
        merged_raw_path = base.raw_path + url.raw_path.lstrip(b"/")
        return base.copy_with(raw_path=merged_raw_path)

    def __init__(
        self,
        *,
        http_url: str,
        method: Literal["GET", "POST", "PUT", "DELETE", "PATCH", "HEAD", "OPTIONS"] = "POST",
        file_path: str | None = None,
        allowed_upload_directory: str | Path | None = None,
        json_data: dict[str, Any] | None = None,
        form_data: dict[str, Any] | None = None,
        params: dict[str, Any] | None = None,
        headers: dict[str, str] | None = None,
        http2: bool | None = None,
        follow_redirects: bool = True,
        callback_function: Callable[..., Any] | None = None,
        max_requests_per_minute: int | None = None,
        custom_configuration: TargetConfiguration | None = None,
        trace_config: TargetTraceConfig | None = None,
        **httpx_client_kwargs: Any,
    ) -> None:
        """
        Force the parent 'HTTPTarget' to skip raw http_request logic by setting http_request=None.

        Args:
            http_url (str): The URL to send the HTTP request to.
            method (str): The HTTP method to use (GET, POST, PUT, DELETE, PATCH, HEAD, OPTIONS). Defaults to "POST".
            file_path (str, Optional): Path to a file to upload. If not provided, we attempt to pull it from the
            prompt's `converted_value`.
            allowed_upload_directory (str | Path | None): Directory containing files this target may upload.
                Required when uploading files. Defaults to None.
            json_data (dict, Optional): JSON data to send in the request body (for POST/PUT/PATCH).
            form_data (dict, Optional): Form data to send in the request body (for POST/PUT/PATCH).
            params (dict, Optional): Query parameters to include in the request URL (for GET/HEAD).
            headers (dict, Optional): Headers to include in the request.
            http2 (bool, Optional): Whether to use HTTP/2. If None, defaults to False.
            follow_redirects (bool): Whether to follow HTTP redirects. Defaults to True for backward compatibility;
                set to False when redirects are unnecessary or the destination must remain fixed.
            callback_function (Callable, Optional): Function to parse the HTTP response.
            max_requests_per_minute (int, Optional): Maximum number of requests per minute.
            custom_configuration (TargetConfiguration, Optional): Override the default configuration for this target
            instance.
            Defaults to None.
            trace_config: Request tracing configuration. Tracing is disabled by default because an
                arbitrary HTTP endpoint is not known to support W3C trace context. Pass
                ``TargetTraceConfig(enabled=True)`` for an instrumented endpoint.
            **httpx_client_kwargs: Additional keyword arguments to pass to the httpx.AsyncClient constructor.

        Raises:
            ValueError: If the HTTP method is invalid.
            ValueError: If file uploads are attempted with an HTTP method that does not support them.
            ValueError: If the allowed upload directory does not exist or is not a directory.
        """
        super().__init__(
            http_request="",
            prompt_regex_string="",
            use_tls=True,
            follow_redirects=follow_redirects,
            callback_function=callback_function,
            max_requests_per_minute=max_requests_per_minute,
            custom_configuration=custom_configuration,
            trace_config=trace_config,
            **httpx_client_kwargs,
        )

        self.http_url = http_url

        base_url = httpx_client_kwargs.get("base_url")
        if not base_url and self._client:
            client_base_url = getattr(self._client, "base_url", None)
            if client_base_url and str(client_base_url):
                base_url = client_base_url

        merge_url = httpx.URL(http_url)
        if merge_url.is_relative_url and base_url and str(base_url):
            resolved_url = self._merge_base_and_url(httpx.URL(base_url), merge_url)
        else:
            resolved_url = merge_url

        self._endpoint = self._redact_url_for_identifier(resolved_url)
        self._destination_origin = self._get_destination_origin(str(resolved_url))
        self.method = method
        self.file_path = file_path
        self.allowed_upload_directory = self._resolve_allowed_upload_directory(allowed_upload_directory)
        self.json_data = json_data
        self.form_data = form_data
        self.params = params
        self.headers = headers or {}
        self.http2 = http2

        # Validate method
        if self.method not in {"GET", "POST", "PUT", "DELETE", "PATCH", "HEAD", "OPTIONS"}:
            raise ValueError(f"Invalid HTTP method: {self.method}")

    def _build_identifier(self) -> ComponentIdentifier:
        """
        Build the identifier with HTTPX API target-specific parameters.

        Returns:
            ComponentIdentifier: The identifier for this target instance.
        """
        return self._create_identifier(
            params={
                "method": self.method,
                "follow_redirects": self.follow_redirects,
                "callback_function": getattr(self.callback_function, "__name__", None),
                "http2": self.http2,
            },
        )

    @limit_requests_per_minute
    async def _send_prompt_to_target_async(self, *, normalized_conversation: list[Message]) -> list[Message]:
        """
        Override the parent's method to skip raw http_request usage,
        and do a standard "API mode" approach.

        - If file_path is set or we can deduce it from the message piece, we upload a file.
        - Otherwise, we send normal requests with JSON or form_data (if provided).

        Returns:
            list[Message]: A list containing the response object with generated text pieces.

        Raises:
            ValueError: If no `http_url` is provided.
            httpx.TimeoutException: If the request times out.
            httpx.RequestError: If the request fails.
            FileNotFoundError: If the specified file to upload is not found.
        """
        message = normalized_conversation[-1]
        message_piece: MessagePiece = message.message_pieces[0]
        upload_path = await self._get_upload_path_async(message_piece=message_piece)
        if upload_path and self.method not in {"POST", "PUT"}:
            raise ValueError(f"File uploads are not allowed with HTTP method: {self.method}")

        if not self.http_url:
            raise ValueError("No `http_url` provided for HTTPXApiTarget.")

        http2_version = self.http2 if self.http2 is not None else False

        async with httpx.AsyncClient(http2=http2_version, **self.httpx_client_kwargs) as client:
            headers = request_trace_headers(request=message, headers=self.headers, default_headers=client.headers)
            try:
                if upload_path:
                    # Handle file upload (only for POST & PUT)
                    filename = upload_path.name
                    mime_type = mimetypes.guess_type(filename)[0] or "application/octet-stream"

                    async with aiofiles.open(upload_path, "rb") as fp:
                        file_bytes = await fp.read()

                    files = {"file": (filename, file_bytes, mime_type)}
                    logger.info(f"HTTPXApiTarget: uploading file={filename} via {self.method} to {self.http_url}")

                    response = await client.request(
                        method=self.method,
                        url=self.http_url,
                        headers=headers,
                        params=self.params,
                        files=files,
                        follow_redirects=self.follow_redirects,
                    )
                else:
                    # No file upload, handle based on HTTP method
                    logger.info(f"HTTPXApiTarget: sending {self.method} to {self.http_url} with possible JSON/form.")
                    response = await client.request(
                        method=self.method,
                        url=self.http_url,
                        headers=headers,
                        params=self.params,
                        json=self.json_data if self.method in {"POST", "PUT", "PATCH"} else None,
                        data=self.form_data if self.method in {"POST", "PUT", "PATCH"} else None,
                        follow_redirects=self.follow_redirects,
                    )

            except httpx.TimeoutException:
                logger.error(f"Timeout error for URL: {self.http_url}")
                raise
            except httpx.RequestError as e:
                logger.error(f"Request failed: {e}")
                raise
            except FileNotFoundError as e:
                logger.error(f"File not found: {self.file_path}. Exception: {e}")
                raise

        response_content = response.text

        # If a callback function was set, let them parse the response
        if self.callback_function:
            response_content = self.callback_function(response=response)

        # Reuse parent's response object construction
        response_entry = construct_response_from_request(
            request=message_piece, response_text_pieces=[str(response_content)]
        )

        return [response_entry]

    async def _get_upload_path_async(self, *, message_piece: MessagePiece) -> Path | None:
        if self.file_path:
            candidate = Path(self.file_path)
        elif message_piece.converted_value_data_type in self._PATH_TYPES:
            candidate = Path(message_piece.converted_value)
        elif await asyncio.to_thread(Path(message_piece.converted_value).is_file):
            candidate = Path(message_piece.converted_value)
            print_deprecation_message(
                old_item="HTTPXAPITarget implicit text-path uploads",
                new_item="a path-typed MessagePiece or explicit file_path",
                removed_in="1.3.0",
            )
        else:
            return None

        if self.allowed_upload_directory is None:
            print_deprecation_message(
                old_item="HTTPXAPITarget file uploads without allowed_upload_directory",
                new_item="HTTPXAPITarget(..., allowed_upload_directory=...)",
                removed_in="1.3.0",
            )
            candidate = await asyncio.to_thread(candidate.resolve)
        else:
            candidate = await asyncio.to_thread(
                self._validate_upload_path,
                path=candidate,
                allowed_directory=self.allowed_upload_directory,
            )
        if not await asyncio.to_thread(candidate.is_file):
            raise FileNotFoundError(f"File not found: {candidate}")
        return candidate

    def _validate_upload_path(self, *, path: Path, allowed_directory: Path) -> Path:
        resolved_path = path.resolve()
        try:
            resolved_path.relative_to(allowed_directory)
        except ValueError as exc:
            raise ValueError(f"File upload path is outside the allowed upload directory: {resolved_path}") from exc
        return resolved_path

    @staticmethod
    def _resolve_allowed_upload_directory(allowed_directory: str | Path | None) -> Path | None:
        if allowed_directory is None:
            return None

        resolved_directory = Path(allowed_directory).resolve()
        if not resolved_directory.is_dir():
            raise ValueError(f"Allowed upload directory does not exist or is not a directory: {allowed_directory}")
        return resolved_directory
